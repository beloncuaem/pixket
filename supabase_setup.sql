-- 10.3 View bạn bè (chỉ id, nickname, avatar_url) — tránh lộ email
CREATE OR REPLACE VIEW public.friend_profiles AS
SELECT p.id, p.nickname, p.avatar_url
FROM public.profiles p
WHERE p.id = auth.uid() OR EXISTS (
    SELECT 1 FROM public.friendships f
    WHERE f.status = 'accepted'
      AND (
        (f.requester_id = auth.uid() AND f.addressee_id = p.id) OR
        (f.addressee_id = auth.uid() AND f.requester_id = p.id)
      )
);

-- 10.4 RPC tìm user theo email (security definer, không lộ danh sách)
CREATE OR REPLACE FUNCTION public.find_user_by_email(p_email text)
RETURNS TABLE (id uuid, nickname text, avatar_url text)
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
    RETURN QUERY
    SELECT p.id, p.nickname, p.avatar_url
    FROM public.profiles p
    WHERE lower(p.email) = lower(trim(p_email))
      AND p.id <> auth.uid();
END;
$$;
GRANT EXECUTE ON FUNCTION public.find_user_by_email(text) TO authenticated;

